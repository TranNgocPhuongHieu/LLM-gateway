func addUsedChannel(c *gin.Context, channelId int) {
	useChannel := c.GetStringSlice("use_channel")
	useChannel = append(useChannel, fmt.Sprintf("%d", channelId))
	c.Set("use_channel", useChannel)
}

func fastTokenCountMetaForPricing(request dto.Request) *types.TokenCountMeta {
	if request == nil {
		return &types.TokenCountMeta{}
	}
	meta := &types.TokenCountMeta{
		TokenType: types.TokenTypeTokenizer,
	}
	switch r := request.(type) {
	case *dto.GeneralOpenAIRequest:
		maxCompletionTokens := lo.FromPtrOr(r.MaxCompletionTokens, uint(0))
		maxTokens := lo.FromPtrOr(r.MaxTokens, uint(0))
		if maxCompletionTokens > maxTokens {
			meta.MaxTokens = int(maxCompletionTokens)
		} else {
			meta.MaxTokens = int(maxTokens)
		}
	case *dto.OpenAIResponsesRequest:
		meta.MaxTokens = int(lo.FromPtrOr(r.MaxOutputTokens, uint(0)))
	case *dto.ClaudeRequest:
		meta.MaxTokens = int(lo.FromPtr(r.MaxTokens))
	case *dto.ImageRequest:
		// Pricing for image requests depends on ImagePriceRatio; safe to compute even when CountToken is disabled.
		return r.GetTokenCountMeta()
	default:
		// Best-effort: leave CombineText empty to avoid large allocations.
	}
	return meta
}

func getChannel(c *gin.Context, info *relaycommon.RelayInfo, retryParam *service.RetryParam) (*model.Channel, *types.NewAPIError) {
	if info.ChannelMeta == nil {
		autoBan := c.GetBool("auto_ban")
		autoBanInt := 1
		if !autoBan {
			autoBanInt = 0
		}
		return &model.Channel{
			Id:      c.GetInt("channel_id"),
			Type:    c.GetInt("channel_type"),
			Name:    c.GetString("channel_name"),
			AutoBan: &autoBanInt,
		}, nil
	}
	channel, selectGroup, err := service.CacheGetRandomSatisfiedChannel(retryParam)
	if err != nil {
		return nil, types.NewError(fmt.Errorf("获取分组 %s 下模型 %s 的可用渠道失败（retry）: %s", selectGroup, info.OriginModelName, err.Error()), types.ErrorCodeGetChannelFailed, types.ErrOptionWithSkipRetry())
	}
	if channel == nil {
		// All distinct candidates failed; keep the actual upstream failure
		// rather than replacing it with a channel-selection error.
		if len(retryParam.AttemptedChannelIDs) > 0 && info.LastError != nil {
			return nil, info.LastError
		}
		return nil, types.NewError(fmt.Errorf("分组 %s 下模型 %s 的可用渠道不存在（retry）", selectGroup, info.OriginModelName), types.ErrorCodeGetChannelFailed, types.ErrOptionWithSkipRetry())
	}

	info.PriceData.GroupRatioInfo = helper.HandleGroupRatio(c, info)

	newAPIError := middleware.SetupContextForSelectedChannel(c, channel, info.OriginModelName)
	if newAPIError != nil {
		return nil, newAPIError
	}
	return channel, nil
}

func shouldRetry(c *gin.Context, openaiErr *types.NewAPIError, retryTimes int) bool {
	if openaiErr == nil {
		return false
	}
	if c.Request.Context().Err() != nil {
		return false
	}
	if service.ShouldSkipRetryAfterChannelAffinityFailure(c) {
		return false
	}
	if types.IsSkipRetryError(openaiErr) {
		return false
	}
	if types.IsChannelError(openaiErr) {
		return true
	}
	if retryTimes <= 0 {
		return false
	}
	if service.GetChannelConstraints(c).SuppressesRetry() {
		return false
	}
	code := openaiErr.StatusCode
	if code >= 200 && code < 300 {
		return false
	}
	if code < 100 || code > 599 {
		return true
	}
	// XPiki can fail before delivering any answer with a malformed HTTP-200
	// body or a provider/gateway timeout. The global legacy policy suppresses
	// these errors, preventing selection of the independent 9router fallback.
	// All cancellation, partial-output, pin and budget guards above still apply.
	if service.IsXPikiBaseURL(common.GetContextKeyString(c, constant.ContextKeyChannelBaseUrl)) &&
		(openaiErr.GetErrorCode() == types.ErrorCodeBadResponseBody || code == http.StatusRequestTimeout || code >= 500) {
		return true
	}
	// 9router timeouts before output may use the independent XPiki channels.
	// Keep the cancellation, partial-output, pin and budget guards above.
	if code == http.StatusRequestTimeout || code == http.StatusGatewayTimeout || code == 524 {
		upstream, err := url.Parse(common.GetContextKeyString(c, constant.ContextKeyChannelBaseUrl))
		if err == nil && upstream.User == nil &&
			(upstream.Scheme == "http" || upstream.Scheme == "https") &&
			(strings.EqualFold(upstream.Hostname(), "9router") || strings.EqualFold(upstream.Hostname(), "9router.trnhieu.dev")) {
			return true
		}
	}
	if operation_setting.IsAlwaysSkipRetryCode(openaiErr.GetErrorCode()) {
		return false
	}
	return operation_setting.ShouldRetryByStatusCode(code)
}

func writeRelayErrorResponse(c *gin.Context, format types.RelayFormat, relayErr *types.NewAPIError) {
	if c.Request.Context().Err() != nil {
		return
	}
	var payload gin.H
	if format == types.RelayFormatClaude {
		payload = gin.H{"type": "error", "error": relayErr.ToClaudeError()}
	} else {
		payload = gin.H{"error": relayErr.ToOpenAIError()}
	}
	if c.Writer.Written() && strings.HasPrefix(c.Writer.Header().Get("Content-Type"), "text/event-stream") {
		// Headers may already be committed by keepalive comments or AI output.
		// Send a terminal SSE error, never append bare JSON or a success [DONE].
		if format == types.RelayFormatClaude || format == types.RelayFormatOpenAIResponses {
			c.Render(-1, common.CustomEvent{Data: "event: error\n"})
		}
		if format == types.RelayFormatOpenAIResponses {
			err := relayErr.ToOpenAIError()
			payload = gin.H{"type": "error", "code": err.Code, "message": err.Message, "param": err.Param}
		}
		_ = helper.ObjectData(c, payload)
		return
	}
	c.Writer.Header().Set("Content-Type", "application/json")
	c.Writer.Header().Del("Transfer-Encoding")
	c.JSON(relayErr.StatusCode, payload)
}

func processChannelError(c *gin.Context, channelError types.ChannelError, err *types.NewAPIError, relayInfo *relaycommon.RelayInfo, final bool) {
	logger.LogError(c, fmt.Sprintf("channel error (channel #%d, status code: %d): %s", channelError.ChannelId, err.StatusCode, common.LocalLogPreview(err.Error())))
	// 不要使用context获取渠道信息，异步处理时可能会出现渠道信息不一致的情况
	// do not use context to get channel info, there may be inconsistent channel info when processing asynchronously
	if service.ShouldDisableChannel(err) && channelError.AutoBan {
		gopool.Go(func() {
			service.DisableChannel(channelError, err.ErrorWithStatusCode())
		})
	}

	if final && constant.ErrorLogEnabled && types.IsRecordErrorLog(err) {
		// 保存错误日志到mysql中
		userId := c.GetInt("id")
		tokenName := c.GetString("token_name")
		modelName := c.GetString("original_model")
		tokenId := c.GetInt("token_id")
		userGroup := c.GetString("group")
		other := model.NewLogOther()
		if c.Request != nil && c.Request.URL != nil {
			other.SetPublic("request_path", c.Request.URL.Path)
		}
		other.SetPublic("error_type", err.GetErrorType())
		other.SetPublic("error_code", err.GetErrorCode())
		other.SetPublic("status_code", err.StatusCode)
		other.SetPublic("request_final", final)
		if err.UpstreamStatusCode > 0 {
			other.SetPublic("upstream_status_code", err.UpstreamStatusCode)
			other.SetPublic("failure_origin", "upstream")
		} else if err.GetErrorType() == types.ErrorTypeNewAPIError {
			other.SetPublic("failure_origin", "gateway")
		}
		other.SetPublic("request_cancelled", c.Request.Context().Err() != nil)
		service.AppendRelayLogAdminInfo(c, relayInfo, other)
		startTime := common.GetContextKeyTime(c, constant.ContextKeyRequestStartTime)
		if startTime.IsZero() {
			startTime = time.Now()
		}
		useTimeSeconds := int(time.Since(startTime).Seconds())
		model.RecordErrorLog(c, userId, channelError.ChannelId, modelName, tokenName, err.MaskSensitiveErrorWithStatusCode(), tokenId, useTimeSeconds, common.GetContextKeyBool(c, constant.ContextKeyIsStream), userGroup, other)
	}

}

